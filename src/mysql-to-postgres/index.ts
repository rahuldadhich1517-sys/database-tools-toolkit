import { tokenizeSQL, Token } from "../shared/sql-tokenizer";

export interface MySQLToPostgresOptions {
  tinyint1AsBoolean?: boolean; // default: true
  useIdentityByDefault?: boolean; // default: true (GENERATED BY DEFAULT AS IDENTITY)
  jsonToJSONB?: boolean; // default: true (JSON -> JSONB)
}

export interface ConversionResult {
  sql: string;
  warnings: string[];
  unsupported: string[];
  success: boolean;
}

const BASE_TYPE_MAPPINGS: Record<string, string> = {
  TINYINT: "SMALLINT",
  SMALLINT: "SMALLINT",
  MEDIUMINT: "INTEGER",
  INT: "INTEGER",
  INTEGER: "INTEGER",
  BIGINT: "BIGINT",
  FLOAT: "REAL",
  DOUBLE: "DOUBLE PRECISION",
  "DOUBLE PRECISION": "DOUBLE PRECISION",
  DECIMAL: "DECIMAL",
  NUMERIC: "NUMERIC",
  CHAR: "CHAR",
  VARCHAR: "VARCHAR",
  TINYTEXT: "TEXT",
  TEXT: "TEXT",
  MEDIUMTEXT: "TEXT",
  LONGTEXT: "TEXT",
  TINYBLOB: "BYTEA",
  BLOB: "BYTEA",
  MEDIUMBLOB: "BYTEA",
  LONGBLOB: "BYTEA",
  BINARY: "BYTEA",
  VARBINARY: "BYTEA",
  DATE: "DATE",
  DATETIME: "TIMESTAMP",
  TIMESTAMP: "TIMESTAMPTZ",
  TIME: "TIME",
  JSON: "JSONB",
  BOOLEAN: "BOOLEAN",
  BOOL: "BOOLEAN",
};

export function getMySQLToPostgresMappings(): Record<string, string> {
  return { ...BASE_TYPE_MAPPINGS };
}

export function convertMySQLTypeToPostgres(
  mysqlType: string,
  options: MySQLToPostgresOptions = {}
): { postgresType: string; warnings: string[] } {
  const { tinyint1AsBoolean = true, jsonToJSONB = true } = options;
  const warnings: string[] = [];
  const trimmed = mysqlType.trim();

  // Check TINYINT(1)
  if (/^tinyint\s*\(\s*1\s*\)/i.test(trimmed)) {
    if (tinyint1AsBoolean) {
      warnings.push("TINYINT(1) converted to BOOLEAN. If this stores numeric data, configure tinyint1AsBoolean: false.");
      return { postgresType: "BOOLEAN", warnings };
    }
    return { postgresType: "SMALLINT", warnings };
  }

  // Check unsigned
  const isUnsigned = /\bunsigned\b/i.test(trimmed);
  const cleanType = trimmed.replace(/\bunsigned\b/gi, "").replace(/\bzerofill\b/gi, "").trim();

  // Extract base type and optional params: e.g. VARCHAR(255) -> base: VARCHAR, args: 255
  const match = cleanType.match(/^([a-zA-Z_]+)(?:\s*\(([^)]+)\))?/);
  if (!match) {
    return { postgresType: cleanType, warnings };
  }

  const baseName = match[1].toUpperCase();
  const typeArgs = match[2]?.trim();

  if (isUnsigned) {
    if (baseName === "TINYINT") {
      warnings.push("TINYINT UNSIGNED widened to SMALLINT in PostgreSQL.");
      return { postgresType: "SMALLINT", warnings };
    }
    if (baseName === "SMALLINT") {
      warnings.push("SMALLINT UNSIGNED widened to INTEGER in PostgreSQL.");
      return { postgresType: "INTEGER", warnings };
    }
    if (baseName === "MEDIUMINT" || baseName === "INT" || baseName === "INTEGER") {
      warnings.push(`${baseName} UNSIGNED widened to BIGINT in PostgreSQL.`);
      return { postgresType: "BIGINT", warnings };
    }
    if (baseName === "BIGINT") {
      warnings.push("BIGINT UNSIGNED converted to NUMERIC(20, 0) because PostgreSQL BIGINT is signed 64-bit.");
      return { postgresType: "NUMERIC(20, 0)", warnings };
    }
  }

  if (baseName === "JSON") {
    return { postgresType: jsonToJSONB ? "JSONB" : "JSON", warnings };
  }

  if (baseName === "ENUM") {
    warnings.push(`ENUM(${typeArgs ?? ""}) converted to TEXT with CHECK constraint recommended.`);
    return { postgresType: "TEXT", warnings };
  }

  if (baseName === "SET") {
    warnings.push(`SET(${typeArgs ?? ""}) converted to TEXT[] in PostgreSQL.`);
    return { postgresType: "TEXT[]", warnings };
  }

  const mappedBase = BASE_TYPE_MAPPINGS[baseName] ?? baseName;
  if (typeArgs && (mappedBase === "VARCHAR" || mappedBase === "CHAR" || mappedBase === "DECIMAL" || mappedBase === "NUMERIC")) {
    return { postgresType: `${mappedBase}(${typeArgs})`, warnings };
  }

  return { postgresType: mappedBase, warnings };
}

function cleanIdentifier(id: string): string {
  let clean = id.trim();
  if (clean.startsWith("`") && clean.endsWith("`")) {
    clean = clean.slice(1, -1);
  }
  return `"${clean.replace(/"/g, '""')}"`;
}

export function convertMySQLToPostgres(
  sql: string,
  options: MySQLToPostgresOptions = {}
): ConversionResult {
  const warnings: string[] = [];
  const unsupported: string[] = [];

  if (!sql || typeof sql !== "string") {
    return {
      sql: "",
      warnings: ["Empty input SQL"],
      unsupported: [],
      success: false,
    };
  }

  const tokens = tokenizeSQL(sql, { includeWhitespace: false, includeComments: false });
  if (tokens.length === 0) {
    return { sql: "", warnings: ["No tokens found in input SQL"], unsupported: [], success: false };
  }

  let i = 0;

  function peek(offset = 0): Token | undefined {
    return tokens[i + offset];
  }

  function consume(): Token {
    return tokens[i++];
  }

  // Expect CREATE [TEMPORARY] TABLE [IF NOT EXISTS] tableName (
  if (tokens[0]?.value.toUpperCase() !== "CREATE") {
    unsupported.push("Only CREATE TABLE statements are supported by this converter");
    return { sql: "", warnings, unsupported, success: false };
  }

  consume(); // CREATE
  let isTemporary = false;
  if (peek()?.value.toUpperCase() === "TEMPORARY") {
    isTemporary = true;
    consume();
  }

  if (peek()?.value.toUpperCase() !== "TABLE") {
    unsupported.push("Expected TABLE keyword after CREATE");
    return { sql: "", warnings, unsupported, success: false };
  }
  consume(); // TABLE

  let ifNotExists = false;
  if (
    peek()?.value.toUpperCase() === "IF" &&
    peek(1)?.value.toUpperCase() === "NOT" &&
    peek(2)?.value.toUpperCase() === "EXISTS"
  ) {
    ifNotExists = true;
    consume();
    consume();
    consume();
  }

  const tableToken = consume();
  const tableName = cleanIdentifier(tableToken.value);

  if (peek()?.value !== "(") {
    unsupported.push("Expected '(' opening table column definitions");
    return { sql: "", warnings, unsupported, success: false };
  }
  consume(); // '('

  const columnLines: string[] = [];
  const tableConstraints: string[] = [];

  // Parse table items separated by commas until matching closing ')'
  while (i < tokens.length && peek()?.value !== ")") {
    const itemTokens: Token[] = [];
    let parenDepth = 0;

    while (i < tokens.length) {
      const cur = peek()!;
      if (cur.value === "(") parenDepth++;
      else if (cur.value === ")") {
        if (parenDepth === 0) break;
        parenDepth--;
      } else if (cur.value === "," && parenDepth === 0) {
        consume(); // consume comma
        break;
      }
      itemTokens.push(consume());
    }

    if (itemTokens.length === 0) continue;

    // Analyze itemTokens: is it a table constraint or column definition?
    const firstWord = itemTokens[0].value.toUpperCase();
    const secondWord = itemTokens[1]?.value.toUpperCase();

    if (firstWord === "PRIMARY" && secondWord === "KEY") {
      // PRIMARY KEY (`col1`, `col2`)
      const pkCols = extractParenthesizedIdentifiers(itemTokens);
      tableConstraints.push(`PRIMARY KEY (${pkCols.map(cleanIdentifier).join(", ")})`);
    } else if (
      (firstWord === "KEY" || firstWord === "INDEX") &&
      secondWord !== "("
    ) {
      // MySQL INDEX `idx_name` (`col`) - In PG, indexes are created separately
      warnings.push(`Inline index "${itemTokens[1]?.value}" ignored in PostgreSQL CREATE TABLE. Create indexes using CREATE INDEX.`);
    } else if (
      (firstWord === "UNIQUE" && secondWord === "KEY") ||
      (firstWord === "UNIQUE" && secondWord === "INDEX") ||
      (firstWord === "UNIQUE" && secondWord !== "(" && itemTokens[2]?.value === "(")
    ) {
      const uCols = extractParenthesizedIdentifiers(itemTokens);
      tableConstraints.push(`UNIQUE (${uCols.map(cleanIdentifier).join(", ")})`);
    } else if (firstWord === "FOREIGN" && secondWord === "KEY") {
      // FOREIGN KEY (`col`) REFERENCES `other` (`col`)
      const fkSql = convertForeignKeyTokens(itemTokens, warnings);
      if (fkSql) tableConstraints.push(fkSql);
    } else if (firstWord === "CONSTRAINT") {
      // CONSTRAINT `name` ...
      const constraintSql = convertConstraintTokens(itemTokens, warnings);
      if (constraintSql) tableConstraints.push(constraintSql);
    } else {
      // Column definition
      const colSql = convertColumnTokens(itemTokens, options, warnings);
      if (colSql) columnLines.push(colSql);
    }
  }

  if (peek()?.value === ")") {
    consume(); // consume closing ')'
  }

  // Check table options after ')' e.g. ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 AUTO_INCREMENT=10
  while (i < tokens.length && peek()?.value !== ";") {
    const optTok = consume();
    const optVal = optTok.value.toUpperCase();
    if (optVal === "ENGINE" || optVal === "CHARSET" || optVal === "COLLATE" || optVal === "AUTO_INCREMENT") {
      warnings.push(`MySQL table option "${optTok.value}" is not applicable in PostgreSQL and was skipped.`);
    }
  }

  const allDefinitions = [...columnLines, ...tableConstraints];
  const tempStr = isTemporary ? "TEMPORARY " : "";
  const ifNotExistsStr = ifNotExists ? "IF NOT EXISTS " : "";

  const formattedOutput = `CREATE ${tempStr}TABLE ${ifNotExistsStr}${tableName} (\n  ${allDefinitions.join(",\n  ")}\n);`;

  return {
    sql: formattedOutput,
    warnings,
    unsupported,
    success: true,
  };
}

function extractParenthesizedIdentifiers(tokens: Token[]): string[] {
  const result: string[] = [];
  const openIdx = tokens.findIndex((t) => t.value === "(");
  if (openIdx === -1) return result;

  for (let j = openIdx + 1; j < tokens.length; j++) {
    const t = tokens[j];
    if (t.value === ")") break;
    if (t.type === "identifier" || (t.type === "keyword" && t.value !== ",")) {
      result.push(t.value);
    }
  }
  return result;
}

function convertColumnTokens(
  tokens: Token[],
  options: MySQLToPostgresOptions,
  warnings: string[]
): string {
  const colName = cleanIdentifier(tokens[0].value);
  let j = 1;

  // Gather type tokens up to NULL, NOT, DEFAULT, AUTO_INCREMENT, PRIMARY, UNIQUE, COMMENT, etc.
  let rawType = "";
  let parenDepth = 0;

  while (j < tokens.length) {
    const val = tokens[j].value.toUpperCase();
    if (parenDepth === 0 && [
      "NOT", "NULL", "DEFAULT", "AUTO_INCREMENT", "PRIMARY", "UNIQUE", "COMMENT", "REFERENCES", "CHECK"
    ].includes(val)) {
      break;
    }
    if (tokens[j].value === "(") parenDepth++;
    if (tokens[j].value === ")") parenDepth--;
    rawType += (rawType.length > 0 && !["(", ")", ","].includes(tokens[j].value) ? " " : "") + tokens[j].value;
    j++;
  }

  const isAutoIncrement = tokens.some((t) => t.value.toUpperCase() === "AUTO_INCREMENT");
  let isPrimaryKey = false;
  let isUnique = false;
  let isNotNull = false;
  let defaultValue: string | undefined;

  while (j < tokens.length) {
    const val = tokens[j].value.toUpperCase();
    if (val === "NOT" && tokens[j + 1]?.value.toUpperCase() === "NULL") {
      isNotNull = true;
      j += 2;
    } else if (val === "NULL") {
      j++;
    } else if (val === "PRIMARY" && tokens[j + 1]?.value.toUpperCase() === "KEY") {
      isPrimaryKey = true;
      j += 2;
    } else if (val === "UNIQUE" || (val === "UNIQUE" && tokens[j + 1]?.value.toUpperCase() === "KEY")) {
      isUnique = true;
      j += (tokens[j + 1]?.value.toUpperCase() === "KEY" ? 2 : 1);
    } else if (val === "AUTO_INCREMENT") {
      j++;
    } else if (val === "DEFAULT") {
      j++;
      if (j < tokens.length) {
        defaultValue = tokens[j].value;
        j++;
      }
    } else if (val === "COMMENT") {
      j += 2; // skip COMMENT and comment string
    } else if (val === "ON" && tokens[j + 1]?.value.toUpperCase() === "UPDATE") {
      warnings.push(`MySQL "ON UPDATE CURRENT_TIMESTAMP" requires a trigger in PostgreSQL and was omitted.`);
      j += (tokens[j + 2]?.value.toUpperCase() === "CURRENT_TIMESTAMP" ? 3 : 2);
    } else {
      j++;
    }
  }

  // Type conversion
  const { postgresType, warnings: typeWarnings } = convertMySQLTypeToPostgres(rawType, options);
  warnings.push(...typeWarnings);

  const parts = [colName];

  if (isAutoIncrement) {
    if (postgresType === "BIGINT") {
      parts.push("BIGINT GENERATED BY DEFAULT AS IDENTITY");
    } else {
      parts.push("INTEGER GENERATED BY DEFAULT AS IDENTITY");
    }
  } else {
    parts.push(postgresType);
  }

  if (isNotNull) {
    parts.push("NOT NULL");
  }

  if (defaultValue !== undefined) {
    const defUpper = defaultValue.toUpperCase();
    if (defUpper === "CURRENT_TIMESTAMP" || defUpper === "NOW()") {
      parts.push("DEFAULT CURRENT_TIMESTAMP");
    } else if (defUpper === "NULL") {
      parts.push("DEFAULT NULL");
    } else {
      parts.push(`DEFAULT ${defaultValue}`);
    }
  }

  if (isPrimaryKey) {
    parts.push("PRIMARY KEY");
  }

  if (isUnique) {
    parts.push("UNIQUE");
  }

  return parts.join(" ");
}

function convertForeignKeyTokens(tokens: Token[], warnings: string[]): string {
  // FOREIGN KEY (`c1`) REFERENCES `t2` (`c2`) [ON DELETE ...] [ON UPDATE ...]
  const fkCols = extractParenthesizedIdentifiers(tokens);
  const refIdx = tokens.findIndex((t) => t.value.toUpperCase() === "REFERENCES");
  if (refIdx === -1 || refIdx + 1 >= tokens.length) {
    warnings.push("Malformed FOREIGN KEY clause");
    return "";
  }

  const refTable = cleanIdentifier(tokens[refIdx + 1].value);
  const refTokens = tokens.slice(refIdx + 1);
  const refCols = extractParenthesizedIdentifiers(refTokens);

  let out = `FOREIGN KEY (${fkCols.map(cleanIdentifier).join(", ")}) REFERENCES ${refTable} (${refCols.map(cleanIdentifier).join(", ")})`;

  // ON DELETE / ON UPDATE
  const fullStr = tokens.map((t) => t.value).join(" ").toUpperCase();
  const onDeleteMatch = fullStr.match(/ON\s+DELETE\s+(CASCADE|RESTRICT|SET\s+NULL|NO\s+ACTION)/);
  if (onDeleteMatch) {
    out += ` ON DELETE ${onDeleteMatch[1]}`;
  }
  const onUpdateMatch = fullStr.match(/ON\s+UPDATE\s+(CASCADE|RESTRICT|SET\s+NULL|NO\s+ACTION)/);
  if (onUpdateMatch) {
    out += ` ON UPDATE ${onUpdateMatch[1]}`;
  }

  return out;
}

function convertConstraintTokens(tokens: Token[], warnings: string[]): string {
  // CONSTRAINT `fk_name` FOREIGN KEY ... or CONSTRAINT `pk_name` PRIMARY KEY ...
  const constraintName = cleanIdentifier(tokens[1].value);
  const rest = tokens.slice(2);
  const firstWord = rest[0]?.value.toUpperCase();

  if (firstWord === "FOREIGN") {
    const fkSql = convertForeignKeyTokens(rest, warnings);
    return `CONSTRAINT ${constraintName} ${fkSql}`;
  }
  if (firstWord === "PRIMARY") {
    const pkCols = extractParenthesizedIdentifiers(rest);
    return `CONSTRAINT ${constraintName} PRIMARY KEY (${pkCols.map(cleanIdentifier).join(", ")})`;
  }
  if (firstWord === "UNIQUE") {
    const uCols = extractParenthesizedIdentifiers(rest);
    return `CONSTRAINT ${constraintName} UNIQUE (${uCols.map(cleanIdentifier).join(", ")})`;
  }

  warnings.push(`Unsupported table constraint: ${tokens.map((t) => t.value).join(" ")}`);
  return "";
}
