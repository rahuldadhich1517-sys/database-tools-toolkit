import { describe, it, expect } from "vitest";
import {
  generateCreateTable,
  validateTableDefinition,
  TableDefinition,
} from "../../src/sql-create-table/index";
import { ValidationError } from "../../src/shared/errors";

describe("SQL Create Table Generator", () => {
  it("generates PostgreSQL CREATE TABLE statement", () => {
    const def: TableDefinition = {
      name: "users",
      columns: [
        { name: "id", type: "BIGINT", autoIncrement: true, primaryKey: true },
        { name: "username", type: "VARCHAR", length: 50, nullable: false, unique: true },
        { name: "email", type: "VARCHAR", length: 100, nullable: false },
        { name: "balance", type: "DECIMAL", precision: 10, scale: 2, default: 0.0 },
        { name: "is_active", type: "BOOLEAN", default: true },
        { name: "created_at", type: "TIMESTAMP", default: "CURRENT_TIMESTAMP" },
      ],
      ifNotExists: true,
    };

    const sql = generateCreateTable(def, "postgres");
    expect(sql).toContain('CREATE TABLE IF NOT EXISTS "users"');
    expect(sql).toContain('"id" BIGINT GENERATED BY DEFAULT AS IDENTITY');
    expect(sql).toContain('"username" VARCHAR(50) NOT NULL UNIQUE');
    expect(sql).toContain('"balance" DECIMAL(10, 2) DEFAULT 0');
    expect(sql).toContain('"is_active" BOOLEAN DEFAULT TRUE');
    expect(sql).toContain('"created_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP');
  });

  it("generates MySQL CREATE TABLE statement with AUTO_INCREMENT", () => {
    const def: TableDefinition = {
      name: "posts",
      columns: [
        { name: "id", type: "INT", autoIncrement: true, primaryKey: true },
        { name: "title", type: "VARCHAR", length: 255, nullable: false },
        { name: "content", type: "TEXT" },
      ],
    };

    const sql = generateCreateTable(def, "mysql");
    expect(sql).toContain("CREATE TABLE `posts`");
    expect(sql).toContain("`id` INT PRIMARY KEY AUTO_INCREMENT");
    expect(sql).toContain("`title` VARCHAR(255) NOT NULL");
  });

  it("generates SQLite CREATE TABLE statement", () => {
    const def: TableDefinition = {
      name: "items",
      columns: [
        { name: "id", type: "INTEGER", autoIncrement: true },
        { name: "name", type: "TEXT", nullable: false },
      ],
    };

    const sql = generateCreateTable(def, "sqlite");
    expect(sql).toContain('CREATE TABLE "items"');
    expect(sql).toContain('"id" INTEGER PRIMARY KEY AUTOINCREMENT');
  });

  it("generates composite primary key and foreign keys", () => {
    const def: TableDefinition = {
      name: "order_items",
      columns: [
        { name: "order_id", type: "BIGINT", nullable: false },
        { name: "item_id", type: "BIGINT", nullable: false },
        { name: "quantity", type: "INT", default: 1 },
      ],
      primaryKey: ["order_id", "item_id"],
      foreignKeys: [
        {
          name: "fk_order",
          columns: ["order_id"],
          referencedTable: "orders",
          referencedColumns: ["id"],
          onDelete: "CASCADE",
        },
      ],
    };

    const sql = generateCreateTable(def, "postgres");
    expect(sql).toContain('PRIMARY KEY ("order_id", "item_id")');
    expect(sql).toContain(
      'CONSTRAINT "fk_order" FOREIGN KEY ("order_id") REFERENCES "orders" ("id") ON DELETE CASCADE'
    );
  });

  it("handles temporary table, unique constraints with names, onUpdate, and type options", () => {
    const def: TableDefinition = {
      name: "temp_items",
      temporary: true,
      columns: [
        { name: "id", type: "INT", primaryKey: true },
        { name: "code", type: "VARCHAR", length: 20, unique: true },
        { name: "rate", type: "NUMERIC", precision: 8, scale: 4, nullable: true },
        { name: "data", type: "BLOB" },
      ],
      uniqueConstraints: [
        { name: "uq_code_rate", columns: ["code", "rate"] },
        { columns: ["rate"] },
      ],
      foreignKeys: [
        {
          name: "fk_items",
          columns: ["id"],
          referencedTable: "parents",
          referencedColumns: ["pid"],
          onDelete: "SET NULL",
          onUpdate: "NO ACTION",
        },
      ],
    };

    const sqlPg = generateCreateTable(def, "postgres");
    expect(sqlPg).toContain('CREATE TEMPORARY TABLE "temp_items"');
    expect(sqlPg).toContain('"rate" NUMERIC(8, 4) NULL');
    expect(sqlPg).toContain('"data" BYTEA');
    expect(sqlPg).toContain('CONSTRAINT "uq_code_rate" UNIQUE ("code", "rate")');
    expect(sqlPg).toContain('UNIQUE ("rate")');
    expect(sqlPg).toContain('ON UPDATE NO ACTION');

    const sqlMy = generateCreateTable(def, "mysql");
    expect(sqlMy).toContain("CREATE TEMPORARY TABLE `temp_items`");
    expect(sqlMy).toContain("`data` BLOB");

    const sqlLite = generateCreateTable(def, "sqlite");
    expect(sqlLite).toContain('CREATE TEMPORARY TABLE "temp_items"');
    expect(sqlLite).toContain('"rate" NUMERIC');
  });

  it("validates table definition and catches errors", () => {
    const valid = validateTableDefinition({
      name: "valid_table",
      columns: [{ name: "id", type: "INT" }],
    });
    expect(valid.valid).toBe(true);

    const invalid = validateTableDefinition({
      name: "bad_table",
      columns: [
        { name: "col1", type: "INT" },
        { name: "col1", type: "VARCHAR" }, // duplicate name
      ],
      primaryKey: ["non_existent_column"],
    });
    expect(invalid.valid).toBe(false);
    expect(invalid.errors.length).toBeGreaterThan(0);
  });

  it("throws ValidationError when generating invalid table", () => {
    expect(() =>
      generateCreateTable({
        name: "empty_table",
        columns: [],
      })
    ).toThrow(ValidationError);
  });
});
