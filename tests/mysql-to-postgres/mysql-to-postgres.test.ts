import { describe, it, expect } from "vitest";
import {
  convertMySQLToPostgres,
  convertMySQLTypeToPostgres,
  getMySQLToPostgresMappings,
} from "../../src/mysql-to-postgres/index";

describe("MySQL to PostgreSQL Converter", () => {
  it("converts basic CREATE TABLE with types and AUTO_INCREMENT to PostgreSQL identity", () => {
    const mysql = `
      CREATE TABLE \`users\` (
        \`id\` int(11) NOT NULL AUTO_INCREMENT,
        \`username\` varchar(50) NOT NULL,
        \`bio\` text,
        \`is_admin\` tinyint(1) DEFAULT 0,
        \`created_at\` datetime DEFAULT CURRENT_TIMESTAMP,
        PRIMARY KEY (\`id\`),
        UNIQUE KEY \`uniq_username\` (\`username\`)
      ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
    `;

    const result = convertMySQLToPostgres(mysql);
    expect(result.success).toBe(true);
    expect(result.sql).toContain('CREATE TABLE "users"');
    expect(result.sql).toContain('"id" INTEGER GENERATED BY DEFAULT AS IDENTITY');
    expect(result.sql).toContain('"username" VARCHAR(50) NOT NULL');
    expect(result.sql).toContain('"bio" TEXT');
    expect(result.sql).toContain('"is_admin" BOOLEAN DEFAULT 0');
    expect(result.sql).toContain('"created_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP');
    expect(result.sql).toContain('PRIMARY KEY ("id")');
    expect(result.sql).toContain('UNIQUE ("username")');
    expect(result.warnings.some((w) => w.includes("ENGINE"))).toBe(true);
  });

  it("handles unsigned type widening", () => {
    const { postgresType: intUnsigned, warnings: w1 } = convertMySQLTypeToPostgres("INT UNSIGNED");
    expect(intUnsigned).toBe("BIGINT");
    expect(w1.length).toBeGreaterThan(0);

    const { postgresType: bigintUnsigned, warnings: w2 } = convertMySQLTypeToPostgres("BIGINT UNSIGNED");
    expect(bigintUnsigned).toBe("NUMERIC(20, 0)");
    expect(w2.length).toBeGreaterThan(0);

    const { postgresType: tinyUnsigned } = convertMySQLTypeToPostgres("TINYINT UNSIGNED");
    expect(tinyUnsigned).toBe("SMALLINT");
  });

  it("converts FOREIGN KEY constraints and ON DELETE actions", () => {
    const mysql = `
      CREATE TABLE \`orders\` (
        \`id\` bigint(20) NOT NULL AUTO_INCREMENT,
        \`user_id\` int(11) NOT NULL,
        PRIMARY KEY (\`id\`),
        CONSTRAINT \`fk_orders_users\` FOREIGN KEY (\`user_id\`) REFERENCES \`users\` (\`id\`) ON DELETE CASCADE
      );
    `;

    const result = convertMySQLToPostgres(mysql);
    expect(result.success).toBe(true);
    expect(result.sql).toContain(
      'CONSTRAINT "fk_orders_users" FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE CASCADE'
    );
  });

  it("handles JSON, ENUM and SET types", () => {
    const { postgresType: jsonType } = convertMySQLTypeToPostgres("JSON");
    expect(jsonType).toBe("JSONB");

    const { postgresType: enumType, warnings } = convertMySQLTypeToPostgres("ENUM('active', 'inactive')");
    expect(enumType).toBe("TEXT");
    expect(warnings.length).toBeGreaterThan(0);
  });

  it("provides mappings dictionary", () => {
    const mappings = getMySQLToPostgresMappings();
    expect(mappings["TINYINT"]).toBe("SMALLINT");
    expect(mappings["DATETIME"]).toBe("TIMESTAMP");
    expect(mappings["JSON"]).toBe("JSONB");
  });

  it("handles unsupported syntax and returns false success", () => {
    const result = convertMySQLToPostgres("DROP TABLE users;");
    expect(result.success).toBe(false);
    expect(result.unsupported.length).toBeGreaterThan(0);
  });

  it("converts TEMPORARY IF NOT EXISTS table with unique and check constraints", () => {
    const ddl = `
      CREATE TEMPORARY TABLE IF NOT EXISTS \`session_cache\` (
        \`token\` varchar(64) NOT NULL,
        \`data\` json,
        \`updated_at\` timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
        \`ref_id\` int(11) DEFAULT NULL,
        CONSTRAINT \`pk_token\` PRIMARY KEY (\`token\`),
        CONSTRAINT \`uq_ref\` UNIQUE (\`ref_id\`)
      );
    `;

    const res = convertMySQLToPostgres(ddl);
    expect(res.success).toBe(true);
    expect(res.sql).toContain('CREATE TEMPORARY TABLE IF NOT EXISTS "session_cache"');
    expect(res.sql).toContain('CONSTRAINT "pk_token" PRIMARY KEY ("token")');
    expect(res.sql).toContain('CONSTRAINT "uq_ref" UNIQUE ("ref_id")');
    expect(res.warnings.some((w) => w.includes("ON UPDATE CURRENT_TIMESTAMP"))).toBe(true);
  });
});
